const slice = (s: string, n = 80) => (s.length > n ? s.slice(0, n) + '...' : s);

function detect41to45(content: string) {
  const findings: any[] = [];
  const paragraphs = content.split(/\n\s*\n/).map(p => p.trim()).filter(Boolean);

  // 41
  const DZ = 300;
  for (let i = 0; i < content.length - DZ; i += 100) {
    const w = content.slice(i, i + DZ);
    const has = /[？！\uFF01\uFF1F\u2026\u2014\u2013;:：\uff1b\uff1a\u3001]|\d{2,}/.test(w);
    if (!has) { findings.push({ r: '41', msg: w.slice(0,30) }); break; }
  }

  // 42
  const di = /[\u2014]/.test(content);
  const si = /(没说话|没出声|沉默|没理|没接)/.test(content);
  const ev = /(你看|那个|这怎么|什么呀|不会吧|瞎说|哪有|骗人|不信)/.test(content);
  const he = /(我\u2026|\u2026\u2026|可能|大概|也许|好像|算是|差不多)/.test(content);
  const ex = /[\uff01]/.test(content);
  if ([di,si,ev,he,ex].filter(Boolean).length === 0) {
    findings.push({ r: '42', msg: 'no human dialogue marks' });
  }

  // 43
  const re43 = /(黑泥|线头|扣子|鞋带|口红|汗渍|指甲缝|腋下|松了|没系|缺了一角|裂口|雪花屏|闪烁|滴水|关不上|后盖不见了|划了一道|照片里没人|歪了|斜了|破洞|褪色|掉了漆|磨破了|起了毛|卷了边|糊了|没信号|空号|占线|没电|误触|按错了|多按了|发错了|打错了|走错了|坐过了)/;
  const c43 = (content.match(re43) || []).length;
  if (c43 < 3 && content.length > 500) {
    findings.push({ r: '43', msg: 'imperfect=' + c43 });
  }

  // 44
  const re44 = /(接着|然后|之后|随即|不久后|不一会儿|片刻后|过了一会儿|很快地|马上)/g;
  const m44 = content.match(re44) || [];
  if (m44.length >= 3) {
    findings.push({ r: '44', msg: 'mech=' + m44.length + ' ' + m44.slice(0,3).join(',') });
  }

  // 45
  const re45 = /\d{2,}|[零一二三四五六七八九十百千万亿两]+(件|个|次|句|根|天|年|岁|块|毛|分|度|米|斤|步|遍|页|行|层|级)?/g;
  const m45 = (content.match(re45) || []).filter((n: string) => n.length >= 2 && !/^第/.test(n) && !/^[一二三四五六七八九十]$/.test(n));
  if (m45.length === 0 && content.length > 800) {
    findings.push({ r: '45', msg: 'no specific numbers' });
  }

  return findings;
}

